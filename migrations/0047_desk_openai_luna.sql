-- OPENAI_LUNA_V1 low-cost market-aware benchmark.
-- Same frozen packet/schema as Terra, separate immutable ledger, no authority.
create table if not exists desk_openai_luna (
  ticker text not null,
  close_time timestamptz not null,
  taken_at timestamptz not null,
  secs_left double precision not null,
  study text not null,
  version integer not null,
  prompt_version text not null,
  model text not null,
  response_id text not null default '',
  input_hash text not null,
  input_packet jsonb not null,
  market_p double precision,
  fair_p double precision,
  p_up double precision not null,
  side text not null,
  conviction integer not null,
  regime text not null,
  strongest_evidence jsonb not null,
  contradictions jsonb not null,
  data_quality text not null,
  would_abstain boolean not null,
  chair_lean text not null,
  yes_ask double precision,
  no_ask double precision,
  entry_cents double precision,
  input_tokens integer,
  output_tokens integer,
  total_tokens integer,
  latency_ms integer not null,
  build_sha text not null default '',
  created_at timestamptz not null default now(),
  primary key (ticker, close_time),
  check (study = 'OPENAI_LUNA_V1'),
  check (side in ('UP', 'DOWN')),
  check (chair_lean in ('UP', 'DOWN', 'WAIT')),
  check (data_quality in ('GOOD', 'DEGRADED', 'POOR')),
  check (p_up >= 0 and p_up <= 1),
  check (market_p is null or (market_p >= 0 and market_p <= 1)),
  check (fair_p is null or (fair_p >= 0 and fair_p <= 1)),
  check (conviction >= 0 and conviction <= 100),
  check (secs_left <= 450 and secs_left > 438),
  check (entry_cents is null or (entry_cents > 0 and entry_cents < 100)),
  check (jsonb_typeof(input_packet) = 'object'),
  check (jsonb_typeof(strongest_evidence) = 'array'),
  check (jsonb_typeof(contradictions) = 'array')
);
create index if not exists desk_openai_luna_taken_idx on desk_openai_luna (taken_at desc);
create index if not exists desk_openai_luna_close_idx on desk_openai_luna (close_time desc);
